import 'dart:io';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:path_provider/path_provider.dart';
import 'package:printing/printing.dart';

import '../case/case_controller.dart';
import 'scanned_document.dart';

class PdfService {
  static Future<File> generatePack({
    required CaseData caseData,
    required List<ScannedDocument> documents,
    required bool isHindi,
  }) async {
    final pdf = pw.Document();

    pdf.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        build: (context) => pw.Center(
          child: pw.Column(
            mainAxisAlignment: pw.MainAxisAlignment.center,
            children: [
              pw.Text(
                'Sambal',
                style: pw.TextStyle(
                  fontSize: 36,
                  fontWeight: pw.FontWeight.bold,
                  color: const PdfColor.fromInt(0xFF5A1D2C),
                ),
              ),
              pw.SizedBox(height: 6),
              pw.Text(
                isHindi ? 'दस्तावेज़ पैक' : 'Document Pack',
                style: const pw.TextStyle(fontSize: 20),
              ),
              pw.SizedBox(height: 40),
              _infoRow(
                isHindi ? 'राज्य / जिला' : 'State / District',
                '${caseData.state} / ${caseData.district}',
              ),
              pw.SizedBox(height: 8),
              _infoRow(
                isHindi ? 'परिस्थिति' : 'Circumstance',
                caseData.circumstance,
              ),
              pw.SizedBox(height: 8),
              _infoRow(
                isHindi ? 'कुल दस्तावेज़' : 'Total documents',
                '${documents.length}',
              ),
              pw.SizedBox(height: 40),
              pw.Divider(),
              pw.SizedBox(height: 12),
              pw.Text(
                isHindi
                    ? 'यह पैक Sambal ऐप द्वारा बनाया गया है।'
                    : 'This pack was generated by the Sambal app.',
                style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700),
              ),
              pw.SizedBox(height: 4),
              pw.Text(
                DateTime.now().toString().split('.').first,
                style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey500),
              ),
            ],
          ),
        ),
      ),
    );

    for (final doc in documents) {
      for (final imagePath in doc.imagePaths) {
        final file = File(imagePath);
        if (!file.existsSync()) continue;
        final bytes = await file.readAsBytes();

        pdf.addPage(
          pw.Page(
            pageFormat: PdfPageFormat.a4,
            margin: const pw.EdgeInsets.all(24),
            build: (context) => pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Text(
                      doc.label,
                      style: pw.TextStyle(
                        fontSize: 16,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                    pw.Text(
                      doc.scannedAt.toString().split('.').first,
                      style: const pw.TextStyle(
                        fontSize: 9,
                        color: PdfColors.grey600,
                      ),
                    ),
                  ],
                ),
                pw.SizedBox(height: 12),
                pw.Expanded(
                  child: pw.Center(
                    child: pw.Image(pw.MemoryImage(bytes), fit: pw.BoxFit.contain),
                  ),
                ),
              ],
            ),
          ),
        );
      }
    }

    final dir = await getApplicationDocumentsDirectory();
    final file = File('${dir.path}/sambal_documents.pdf');
    await file.writeAsBytes(await pdf.save());
    return file;
  }

  static pw.Widget _infoRow(String label, String value) {
    return pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.center,
      children: [
        pw.Text('$label: ', style: const pw.TextStyle(fontSize: 13, color: PdfColors.grey700)),
        pw.Text(value, style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold)),
      ],
    );
  }

  static Future<void> printPack(File pdfFile) async {
    await Printing.layoutPdf(onLayout: (_) => pdfFile.readAsBytes());
  }

  static Future<void> sharePack(File pdfFile) async {
    await Printing.sharePdf(
      bytes: await pdfFile.readAsBytes(),
      filename: 'sambal_documents.pdf',
    );
  }
}
